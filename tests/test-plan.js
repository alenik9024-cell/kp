'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
assert.ok(fs.existsSync(require('node:path').join(__dirname,'../kp-plan.js')), 'structured plan module must exist');
const P = require('../kp-plan.js');
const launch = 'Запуск отдела продаж под ключ';
const transform = 'Трансформация имеющегося отдела продаж';
assert.ok(P.isPlanItem({title:launch}));
assert.ok(P.isPlanItem({title:transform}));
assert.ok(!P.isPlanItem({title:'CRM'}));
const a=P.createPlan('launch'), b=P.createPlan('transform');
assert.notEqual(a.objective,b.objective);
for(const key of ['team','routing','management','stages','metrics','assumptions']) assert.ok(a[key].length);
assert.equal(a.version,1);
console.log('PASS: activation, independent mode presets and structured schema');
assert.equal(typeof P.applyPreset,'function','safe preset application exists');
a.objective='Manual objective'; a.stages[0].work='Manual work'; a.stages[1].visible=false;
a.stages.reverse(); a.metrics=[];
a.config.mode='transform';
const changed=P.applyPreset(a,false);
assert.equal(changed.objective,'Manual objective');
assert.equal(changed.stages.find(r=>r.id==='stage-1').work,'Manual work');
assert.equal(changed.stages.find(r=>r.id==='stage-2').visible,false);
assert.equal(changed.stages[0].id,'stage-4');
assert.equal(changed.metrics.length,0);
assert.equal(P.applyPreset(a,true).objective,b.objective);
const old={title:launch,price:'160000',custom:'preserved'};
const migrated=P.migrateItem(old);
assert.equal(migrated.price,old.price); assert.equal(migrated.custom,'preserved');
assert.ok(migrated.plan); assert.ok(!old.plan);
assert.deepEqual(P.migrateItem(JSON.parse(JSON.stringify(migrated))),migrated);
const html=P.renderPlan(Object.assign({},a,{objective:'<img src=x onerror=alert(1)>',value:'"<&'}));
assert.ok(!html.includes('<img')); assert.ok(html.includes('&lt;img'));
assert.ok(!html.includes('remote')); assert.ok(!html.includes('Manual work')===false);
assert.ok(!P.renderPlan(Object.assign({},a,{stages:[{...a.stages[0],visible:false,title:'SECRET'}]})).includes('SECRET'));
assert.throws(()=>P.migratePlan({stages:'invalid'},'launch'));
assert.throws(()=>P.migratePlan({version:999},'launch'));
console.log('PASS: preset preservation/reset, migration, round-trip, visibility, escaping, validation');
